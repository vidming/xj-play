async () => {
  const X=window.XJ, checks=[];
  const ensure=(value,message)=>{if(!value)throw Error(message);};
  const click=selector=>{const element=document.querySelector(selector);ensure(element,`Missing ${selector}`);element.click();};
  const submit=id=>{const form=document.getElementById(id);ensure(form,`Missing ${id}`);form.requestSubmit();};
  const fresh=(route='store',mode='normal',verified=false)=>{X.S={...X.initial(),auth:verified,verified};X.go(route,mode);};
  const confirm=id=>{document.getElementById(id).checked=true;};
  fresh();click('[data-action="trial"]');
  ensure(X.route==='run'&&!X.S.auth,'Guest trial must not require login');
  click('[data-action="boundary"]');click('[data-action="purchase"]');
  ensure(X.route==='login','Purchase must identify first');
  submit('identity-form');ensure(X.route==='verify'&&!X.S.verified,'Verification is separate');
  click('[data-action="verify"]');ensure(X.route==='import','Import choice must remain');
  click('[data-action="skip-import"]');ensure(X.route==='checkout'&&!X.S.imported,'Import can be skipped');
  confirm('purchase-confirm');submit('checkout-form');
  ensure(X.mode==='unknown'&&!X.S.grants.ga,'Unknown payment cannot grant');
  click('[data-action="query-order"]');ensure(X.mode==='paid'&&!X.S.grants.ga,'Cash and grant separate');
  click('[data-action="query-order"]');ensure(X.mode==='delivered'&&X.S.grants.ga,'Simulated delivery must be explicit');
  click('[data-action="enter"]');ensure(X.route==='run','Return to shell');
  checks.push('Guest trial -> boundary -> login -> verification -> skip import -> unknown -> paid -> delivered -> shell');
  X.S.game='gb';X.go('detail');ensure(!X.S.grants.gb,'No cross-game grant');
  checks.push('Game grants stay separate');
  for(const [mode,due,result] of [['free',0,'free'],['zero',0,'zero'],['credit',1800,'unknown']]) {
    fresh('checkout',mode,true);confirm('purchase-confirm');submit('checkout-form');
    ensure(X.S.orders.ga.due===due&&X.mode===result,`Wrong ${mode} branch`);
    if(mode==='credit'){click('[data-action="query-order"]');ensure(document.getElementById('main').innerText.includes('¥18.00'),'Upgrade cash must stay 18');}
  }
  checks.push('Free and zero-cash grants have no channel payment; credit upgrade uses only new cash');
  fresh('checkout','normal',true);X.S.grants.ga=true;
  confirm('purchase-confirm');submit('checkout-form');ensure(X.route==='library'&&!X.S.orders.ga,'No duplicate creation');
  checks.push('Repeated purchase returns existing grant');
  fresh('order','refund',true);click('[data-action="query-order"]');
  ensure(X.mode==='refund'&&document.getElementById('main').innerText.includes('撤权异常'),'No refund fact rewrite');
  checks.push('Refund result and rights exception remain separate');
  fresh('saves','normal',true);X.S.verified=false;X.go('saves');
  ensure(!document.querySelector('table')&&document.getElementById('main').innerText.includes('验证邮箱'),'Unverified private save guard');
  X.S.verified=true;X.go('account');click('[data-action="logout"]');X.go('saves');
  ensure(!document.querySelector('table'),'Logout hides private data');
  checks.push('Unverified and logged-out contexts hide private save details');
  fresh('deletion','normal',true);click('[data-action="identify-delete"]');
  confirm('delete-confirm');submit('delete-confirm-form');ensure(X.S.deletion,'Application stage');
  X.go('checkout');ensure(!document.getElementById('checkout-form'),'Application blocks new assets');
  X.go('saves');ensure(!document.querySelector('table'),'Application freezes writes');
  X.go('deletion','requested');click('[data-action="withdraw-delete"]');ensure(!X.S.deletion&&X.S.auth,'Withdrawal before final');
  X.go('deletion','final');confirm('delete-confirm');submit('delete-confirm-form');
  ensure(!X.S.auth&&X.mode==='cleanup','Final confirmation immediately stops account access');
  checks.push('Deletion application, restrictions, withdrawal, final stop and classified cleanup');
  fresh('ops/publish','blocked',true);confirm('publish-confirm');submit('publish-form');
  ensure(X.mode==='blocked','Missing checks cannot publish');
  fresh('ops/preview','denied',true);ensure(!document.querySelector('table')&&!document.querySelector('.panel'),'Denied preview hides draft');
  checks.push('Publishing gaps block and denied preview reveals no draft');
  fresh('ops/products','normal',true);document.getElementById('product-scopes').value='a,a';
  submit('product-form');ensure(document.getElementById('notice').innerText.includes('不重复'),'Duplicate scopes rejected');
  document.getElementById('product-scopes').value='base-complete';submit('product-form');
  ensure(document.getElementById('notice').innerText.includes('已检查'),'Valid mapping accepted in simulation');
  checks.push('Scope duplicates reject without losing form; valid ASCII sample passes');
  fresh('ops/finance','negative',true);
  ensure(document.getElementById('main').innerText.includes('¥-5.00')&&document.getElementById('main').innerText.includes('费用仍待核对'),'Negative provisional net');
  X.go('ops/finance','known');ensure(document.getElementById('main').innerText.includes('¥45.10'),'Known fee reconciliation');
  checks.push('Unknown fees, negative cross-period net and known-fee sample reconcile');
  fresh('store');document.getElementById('query').value='线索';submit('search-form');
  ensure(document.querySelectorAll('.game-row').length===1&&location.hash.includes('q='),'Filter source in URL');
  X.go('detail');X.go('store');
  ensure(X.S.query==='线索'&&document.querySelectorAll('.game-row').length===1,'Return keeps query');
  document.getElementById('query').value='😀'.repeat(81);submit('search-form');
  ensure(document.getElementById('notice').innerText.includes('80')&&document.getElementById('query').value.length>80,'Codepoint bound preserves input');
  checks.push('Search, shareable query, return and Unicode length feedback');
  fresh('support','normal',true);document.getElementById('support-reason').value='无法交付或运行';
  document.getElementById('support-text').value='模拟交付问题';submit('support-form');
  ensure(X.mode==='submitted','Support entry must produce a progress screen');
  fresh('run');click('[data-action="mute"]');click('[data-action="expand"]');
  ensure(!X.S.mute&&X.S.large&&!document.querySelector('audio,video,iframe'),'No sound or game loaded');
  checks.push('Support progress, mute and expansion interactions');
  X.S=X.initial();X.go('store');
  return {scope:'Only simulated design interactions; no real services',passed:checks.length,checks};
}
